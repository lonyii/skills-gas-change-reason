_CODE_RE = re.compile(r"^([A-Za-z]{2})(\d{2})([A-Z])(\d+)$")


def parse_code(code):
    """解析工程编号。

    返回 dict 或 None：
      {company, company_name, year, cat, cat_name, group, seq, raw}
    """
    s = str(code or "").strip()
    m = _CODE_RE.match(s)
    if not m:
        return None
    comp, yy, cat, seq = m.groups()
    cat_name, group = CATEGORY.get(cat, ("未知类别", "其他"))
    return {
        "raw": s,
        "company": comp.upper(),
        "company_name": REGION.get(comp.upper(), ""),
        "year": int(yy),
        "cat": cat,
        "cat_name": cat_name,
        "group": group,
        "seq": seq,
    }


def category_of(code):
    """取工程编号的细分类型名，如 '工业'。"""
    p = parse_code(code)
    return p["cat_name"] if p else ""


def group_of(code):
    """取工程编号的归一类别，如 '工业' / '市政' / '小区'。"""
    p = parse_code(code)
    return p["group"] if p else ""


def profile(code):
    """取该工程类别的场景与典型变更缘由。"""
    g = group_of(code)
    return CATEGORY_PROFILE.get(g, {"scene": "该工程", "causes": [], "note": ""})


def describe(code):
    """一句话描述工程编号含义，用于 analyze 输出。"""
    p = parse_code(code)
    if not p:
        return ""
    parts = []
    if p["company_name"]:
        parts.append(p["company_name"])
    parts.append("20%s年" % p["year"])
    parts.append(p["cat_name"])
    return "（%s）" % " ".join(parts)
